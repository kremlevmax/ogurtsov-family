-- Явный признак "человек умер", отдельно от точности даты смерти.
-- Раньше "жив/умер" вычислялось из наличия и точности death_date_*,
-- что не позволяло записать "точно умер, но дата смерти неизвестна".
-- По умолчанию false: все существующие и новые люди считаются живыми,
-- пока редактор явно не отметит обратное.

alter table people
  add column is_deceased boolean not null default false;
