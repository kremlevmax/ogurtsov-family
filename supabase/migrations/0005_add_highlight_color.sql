-- Отдельная от branch_color (0004) отметка: подсвечивает ровно ОДНОГО
-- человека в дереве, без наследования кровными потомками — для случаев,
-- когда родоначальник ветки тут ни при чём, просто хочется выделить
-- конкретную карточку. Взаимоисключающе с branch_color на уровне
-- валидации формы (lib/validation/person.ts) — человек либо
-- родоначальник ветки, либо просто подсвечен, не оба сразу.
alter table people
  add column highlight_color text
  check (highlight_color is null or highlight_color ~ '^#[0-9a-fA-F]{6}$');
